def with_launch_cost(inputs: dict[str, M.Parameter], cost: float) -> dict[str, M.Parameter]:
    """Return a shallow-copy with launch_cost overridden to `cost` $/kg."""
    p = inputs["launch_cost"]
    out = dict(inputs)
    out["launch_cost"] = M.Parameter(
        name=p.name,
        placeholder_value=cost,
        placeholder_range=p.placeholder_range,
        units=p.units,
        tier=M.Tier.T5,  # treat as committed for scenario point
        source_locator=p.source_locator,
        notes=f"scenario override: {cost} (original tier {p.tier.name})",
    )
    return out


