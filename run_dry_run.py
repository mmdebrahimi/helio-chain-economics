# Cost inputs: lower value = more favorable for helio chain economics
COST_PARAMS = {
    "launch_cost",
    "areal_density",
    "station_keeping_dv",
    "rectenna_footprint",
    "in_space_manufacturing_cost_multiplier",
    "radiator_areal_density",  # added 2026-05-24: heavier radiator surface = worse economics
}


def scenario_value(name: str, p: M.Parameter, mode: str) -> float:
    """Return parameter value for a scenario mode in {best, median, worst}.

    For COST params: best = low end of range; worst = high end.
    For BENEFIT params (default): best = high end; worst = low end.
    Median = midpoint.
    """
    lo, hi = p.placeholder_range
    if mode == "median":
        return (lo + hi) / 2.0
    is_cost = name in COST_PARAMS
    if mode == "best":
        return lo if is_cost else hi
    elif mode == "worst":
        return hi if is_cost else lo
    raise ValueError(f"Unknown scenario mode: {mode}")


def build_scenario(inputs: dict[str, M.Parameter], mode: str) -> dict[str, M.Parameter]:
    """Build a fully-pinned input dict for the given scenario mode."""
    out_inputs: dict[str, M.Parameter] = {}
    for name, p in inputs.items():
        v = scenario_value(name, p, mode)
        out_inputs[name] = M.Parameter(
            name=p.name,
            placeholder_value=v,
            placeholder_range=p.placeholder_range,
            units=p.units,
            tier=M.Tier.T5,
            source_locator=p.source_locator,
            notes=f"scenario={mode} pin (original tier {p.tier.name})",
        )
    return out_inputs


